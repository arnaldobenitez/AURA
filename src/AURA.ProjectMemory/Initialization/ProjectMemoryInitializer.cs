using AURA.ProjectMemory.Diagnostics;
using AURA.ProjectMemory.Manifest;
using AURA.ProjectMemory.Schemas;
using AURA.ProjectMemory.Templates;

namespace AURA.ProjectMemory.Initialization;

/// <summary>
/// Initializes the AURA Project Memory Core (AURA_PROJECT_MEMORY v1.0 §7.1) on a directory.
/// Never creates optional modules, never overwrites an existing installation, and never
/// regenerates <c>projectId</c> for a project that already has one.
/// </summary>
public static class ProjectMemoryInitializer
{
    private static readonly string[] CoreFilesToCheck =
    [
        "AURA.md",
        ".aura/project.json",
        "docs/00-PROYECTO.md",
        "docs/01-ESTADO-ACTUAL.md"
    ];

    public static ProjectInitResult Init(string path, string? projectName = null)
    {
        var projectRoot = Path.GetFullPath(path);

        var conflicts = DetectConflicts(projectRoot);
        if (conflicts.Count > 0)
        {
            return new ProjectInitResult(false, projectRoot, null, conflicts);
        }

        var resolvedName = string.IsNullOrWhiteSpace(projectName)
            ? new DirectoryInfo(projectRoot).Name
            : projectName;

        var projectId = Guid.NewGuid().ToString();
        var createdAt = DateTimeOffset.UtcNow.ToString("O");

        var manifest = new ProjectManifest(
            ProjectManifest.CurrentSchemaVersion,
            ProjectManifest.CurrentProjectMemoryVersion,
            projectId,
            resolvedName,
            new ProjectDocumentation(
                "docs/00-PROYECTO.md",
                "docs/01-ESTADO-ACTUAL.md",
                "docs/historial",
                new Dictionary<string, string>()),
            createdAt);

        var manifestJson = ProjectManifestSerializer.ToJson(manifest);
        var manifestNode = ProjectManifestSerializer.ParseToNode(manifestJson);
        var manifestElement = System.Text.Json.JsonSerializer.SerializeToElement(manifestNode);
        var manifestValidation = ManifestSchemaProvider.ProjectSchema.Evaluate(manifestElement);

        if (!manifestValidation.IsValid)
        {
            return new ProjectInitResult(false, projectRoot, null, [
                new Diagnostic(
                    DiagnosticSeverity.Error,
                    DiagnosticCode.InvalidProjectManifest,
                    "Internal error: the manifest generated by the initializer does not conform to " +
                    "project.schema.json. This is a defect in the tool, not in the target directory.")
            ]);
        }

        try
        {
            // Preflight already ran above (conflict detection). Write in an order that leaves the
            // directory looking uninitialized (per PROJECT_ROOT detection, which keys on
            // .aura/project.json) if the process is interrupted before the last step.
            Directory.CreateDirectory(projectRoot);
            Directory.CreateDirectory(Path.Combine(projectRoot, ".aura"));
            Directory.CreateDirectory(Path.Combine(projectRoot, "docs"));
            Directory.CreateDirectory(Path.Combine(projectRoot, "docs", "historial"));

            File.WriteAllText(Path.Combine(projectRoot, "AURA.md"), TemplateProvider.GetAuraMd());
            File.WriteAllText(Path.Combine(projectRoot, "docs", "00-PROYECTO.md"), TemplateProvider.GetProyectoTemplate());
            File.WriteAllText(Path.Combine(projectRoot, "docs", "01-ESTADO-ACTUAL.md"), TemplateProvider.GetEstadoActualTemplate());

            // project.json is written last: its existence is what PROJECT_ROOT detection and
            // re-running init both use to decide "this project is already initialized".
            File.WriteAllText(Path.Combine(projectRoot, ".aura", "project.json"), manifestJson);
        }
        catch (IOException ex)
        {
            return new ProjectInitResult(false, projectRoot, null, [
                new Diagnostic(DiagnosticSeverity.Error, DiagnosticCode.InvalidProjectManifest,
                    $"Initialization failed while writing files: {ex.Message}")
            ]);
        }
        catch (UnauthorizedAccessException ex)
        {
            return new ProjectInitResult(false, projectRoot, null, [
                new Diagnostic(DiagnosticSeverity.Error, DiagnosticCode.InvalidProjectManifest,
                    $"Initialization failed due to insufficient permissions: {ex.Message}")
            ]);
        }

        return new ProjectInitResult(true, projectRoot, projectId, []);
    }

    private static List<Diagnostic> DetectConflicts(string projectRoot)
    {
        var conflicts = new List<Diagnostic>();
        var manifestPath = Path.Combine(projectRoot, ".aura", "project.json");
        var hasManifest = File.Exists(manifestPath);

        if (!hasManifest)
        {
            var partialFiles = CoreFilesToCheck
                .Where(relative => relative != ".aura/project.json")
                .Where(relative => File.Exists(Path.Combine(projectRoot, relative.Replace('/', Path.DirectorySeparatorChar))))
                .ToList();

            if (partialFiles.Count > 0)
            {
                conflicts.Add(new Diagnostic(
                    DiagnosticSeverity.Error,
                    DiagnosticCode.PartialInitialization,
                    "Partial Project Memory initialization detected without .aura/project.json. " +
                    $"Existing Core files: {string.Join(", ", partialFiles)}. No files were changed.",
                    partialFiles[0],
                    "Review or move the existing files manually, then run init again; automatic repair is not performed."));
            }
        }
        else
        {
            foreach (var relative in CoreFilesToCheck)
            {
                var absolute = Path.Combine(projectRoot, relative.Replace('/', Path.DirectorySeparatorChar));
                if (File.Exists(absolute))
                {
                    conflicts.Add(new Diagnostic(
                        DiagnosticSeverity.Error,
                        DiagnosticCode.AlreadyInitialized,
                        $"'{relative}' already exists. Project Memory init does not overwrite an existing installation.",
                        relative,
                        "Run validate instead, or remove/rename the conflicting file if you intend to re-initialize."));
                }
            }
        }

        var historyPath = Path.Combine(projectRoot, "docs", "historial");
        if (File.Exists(historyPath))
        {
            conflicts.Add(new Diagnostic(
                DiagnosticSeverity.Error,
                DiagnosticCode.HistoryNotDirectory,
                "'docs/historial' exists as a file, not a directory.",
                "docs/historial"));
        }

        return conflicts;
    }
}
